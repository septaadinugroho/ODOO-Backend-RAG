"""Guard against drift between the SQLAlchemy models and the live Postgres schema.

`conftest.py` runs the suite on SQLite so it needs no container. That buys speed
but leaves one gap: the DDL that Postgres actually applies lives in
`db/init/001_schema.sql`, generated by `scripts/gen_sql.py` from the models. If
someone edits the SQL by hand, or changes a model without regenerating, the two
can diverge silently — and every other test would still pass, because they never
touch Postgres.

This test closes that gap by reflecting the running Postgres schema and comparing
it, table by table, against `Base.metadata`. It is the one test that needs a real
database, so it **skips cleanly** when Postgres is unreachable rather than failing:
run it after `docker compose up -d`, or point it at any instance with

    TEST_DATABASE_URL=postgresql+psycopg2://classbot:classbot@127.0.0.1:5433/classbot \
        pytest tests/test_schema_matches_orm.py

What it checks: every model table exists; each table's column *names* match; each
column's nullability matches; and the constraints and indexes the models name
explicitly — the https CHECK, the record-id pattern CHECK, the education-stage
CHECK, and the composite facet index — are actually present. Those are the
structures the guarantees in FR-9/FR-16/V1/V3 lean on, so a drop is exactly the
kind of drift worth failing over.
"""

from __future__ import annotations

import os

import pytest

pytest.importorskip("sqlalchemy")

from sqlalchemy import create_engine, inspect  # noqa: E402
from sqlalchemy.engine import Engine  # noqa: E402

from app.infrastructure.models import Base  # noqa: E402

DEFAULT_URL = "postgresql+psycopg2://classbot:classbot@127.0.0.1:5433/classbot"


def _postgres_engine_or_skip() -> Engine:
    """A live Postgres engine, or a skipped test with a helpful reason."""
    url = os.environ.get("TEST_DATABASE_URL", DEFAULT_URL)
    if url.startswith("sqlite"):
        pytest.skip(
            "TEST_DATABASE_URL points at SQLite; this test needs Postgres. "
            "Run `docker compose up -d` and unset it, or set it to the "
            "Postgres URL."
        )
    try:
        engine = create_engine(url)
        conn = engine.connect()
    except Exception as exc:  # pragma: no cover - environment dependent
        pytest.skip(f"Postgres not reachable at {url!r}: {exc}")
    else:
        conn.close()
        return engine


@pytest.fixture(scope="module")
def inspector():
    engine = _postgres_engine_or_skip()
    insp = inspect(engine)
    existing = set(insp.get_table_names())
    if "class_records" not in existing:
        pytest.skip(
            "Postgres is reachable but the schema is not initialised "
            "(no class_records table). Apply db/init/*.sql, e.g. via "
            "`docker compose up -d` or scripts/init_db.py, then re-run."
        )
    return insp


def _model_tables():
    return Base.metadata.tables


def test_every_model_table_exists(inspector):
    present = set(inspector.get_table_names())
    expected = set(_model_tables().keys())
    missing = expected - present
    assert not missing, f"tables defined in models but absent from Postgres: {missing}"


def test_column_names_match(inspector):
    for name, table in _model_tables().items():
        db_columns = {c["name"] for c in inspector.get_columns(name)}
        model_columns = {c.name for c in table.columns}
        assert model_columns == db_columns, (
            f"column drift on {name}: "
            f"only-in-model={model_columns - db_columns}, "
            f"only-in-db={db_columns - model_columns}"
        )


def test_column_nullability_matches(inspector):
    for name, table in _model_tables().items():
        db_nullable = {c["name"]: c["nullable"] for c in inspector.get_columns(name)}
        for column in table.columns:
            # A primary key is NOT NULL regardless of how it is spelled; skip the
            # comparison there to avoid reflecting dialect quirks as drift.
            if column.primary_key:
                continue
            assert db_nullable.get(column.name) == column.nullable, (
                f"{name}.{column.name}: model nullable={column.nullable}, "
                f"db nullable={db_nullable.get(column.name)}"
            )


def test_named_check_constraints_present(inspector):
    """The three CHECKs the data guarantees depend on must exist in Postgres.

    SQLite does not enforce or reflect these the same way, which is precisely why
    they are verified against Postgres and not in the SQLite suite.
    """
    expected = {
        "providers": {"ck_provider_url_https"},        # V3: https-only source URLs
        "class_records": {"ck_record_id_pattern", "ck_education_stage"},  # V1
    }
    for table, names in expected.items():
        found = {c["name"] for c in inspector.get_check_constraints(table)}
        missing = names - found
        assert not missing, f"CHECK constraints missing on {table}: {missing}"


def test_named_indexes_present(inspector):
    """The composite facet index and the verified_on index back FR-11 retrieval."""
    found = {idx["name"] for idx in inspector.get_indexes("class_records")}
    for expected in ("ix_class_records_facets", "ix_class_records_verified_on"):
        assert expected in found, f"index {expected!r} missing from class_records"


def test_synonym_unique_constraint_present(inspector):
    """(term, facet) is unique — the dictionary mirror must not hold duplicates."""
    uniques = {
        tuple(uc["column_names"])
        for uc in inspector.get_unique_constraints("synonyms")
    }
    named = {uc["name"] for uc in inspector.get_unique_constraints("synonyms")}
    assert ("term", "facet") in uniques or "uq_synonym_term_facet" in named
